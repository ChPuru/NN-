"""Turn ``weights.npz`` into ``web/model.js``, and optionally one shareable HTML file.

    python3 phase0/export_web.py                       # -> phase0/web/model.js
    python3 phase0/export_web.py --inline              # -> phase0/mnist_demo.html
    python3 phase0/export_web.py --synthetic-weights   # fabricate weights, no training

**Why a ``.js`` file and not ``.json``.** ``fetch()`` -- and ``XMLHttpRequest``,
and ES module ``import`` -- are blocked on ``file://`` by Chrome and Firefox:
every ``file://`` document gets an opaque origin, so a same-origin read of a
sibling file is a cross-origin read and CORS denies it. A plain
``<script src="model.js">`` tag is not subject to that rule, so shipping the
weights as ``const MODEL = {...}`` is what makes a double-clicked
``index.html`` work with no web server anywhere.

The weights are written as decimal literals with 9 significant digits and wrapped
in ``Float32Array.from([...])``. 9 is ``FLT_DECIMAL_DIG``, the round-trip
precision of ``float32``: parse those digits and round to float32 and you recover
the original bits exactly. The ``Float32Array`` is what makes the rounding
happen -- as a plain JS array the literals would stay float64 and sit about
1e-9 away from the trained weights, which is harmless but would leave the
consistency check below measuring decimal truncation instead of layout.

The check itself: after writing the file, the exported numbers are parsed back
out of the generated JavaScript, reshaped the way ``app.js`` indexes them
(``W1[i * n_hidden + j]``, row-major), and the forward pass is re-run with
explicit scalar loops -- the same arithmetic the browser will do. It is compared
against the vectorized NumPy forward. Anything above ~1e-13 means the flattening
order, the bias broadcast, or the serialization disagrees with the JS, and the
demo would be confidently wrong rather than obviously broken.
"""

from __future__ import annotations

import argparse
import os
import re

import numpy as np
from scratchnn import MLP

__all__ = [
    "consistency_check",
    "export",
    "format_array",
    "inline_html",
    "js_equivalent_forward",
    "numpy_forward",
    "parse_model_js",
    "render_model_js",
]

_HERE = os.path.dirname(os.path.abspath(__file__))
_WEB = os.path.join(_HERE, "web")


def format_array(a: np.ndarray) -> str:
    """Flatten to row-major float32 decimals inside a ``Float32Array.from([...])``.

    9 digits is not a round number chosen for looks: it is ``FLT_DECIMAL_DIG``,
    the smallest count that makes float32 -> text -> float32 the identity. At 8
    the demo would silently differ from the trained model in the last bits, and
    the consistency check would have to be loosened to hide it.
    """
    flat = np.asarray(a, dtype=np.float32).reshape(-1)
    body = ",".join(f"{float(v):.9g}" for v in flat)
    return f"Float32Array.from([{body}])"


def render_model_js(
    W1: np.ndarray, b1: np.ndarray, W2: np.ndarray, b2: np.ndarray, test_accuracy: float
) -> str:
    """Render the ``const MODEL = {...}`` source that ``index.html`` script-tags in."""
    n_in, n_hidden = W1.shape
    n_out = W2.shape[1]
    return (
        "// Generated by phase0/export_web.py. Do not edit by hand.\n"
        "// Loaded with a plain <script src> tag: fetch() is blocked on file://,\n"
        "// so the weights have to arrive as executable JS, not as JSON.\n"
        "// Weights are row-major: W1[i * nHidden + j], W2[j * nOut + k].\n"
        "// Float32Array: the 9-digit decimals round back to the trained bits exactly.\n"
        "const MODEL = {\n"
        f'  arch: "{n_in}-{n_hidden}-{n_out}",\n'
        f"  nIn: {n_in}, nHidden: {n_hidden}, nOut: {n_out},\n"
        f"  testAccuracy: {float(test_accuracy):.6f},\n"
        f"  params: {int(W1.size + b1.size + W2.size + b2.size)},\n"
        f"  W1: {format_array(W1)},\n"
        f"  b1: {format_array(b1)},\n"
        f"  W2: {format_array(W2)},\n"
        f"  b2: {format_array(b2)}\n"
        "};\n"
    )


def parse_model_js(source: str) -> dict[str, object]:
    """Read the arrays and scalars back out of generated ``model.js`` text.

    Deliberately parses the *emitted text* rather than reusing the in-memory
    arrays: a serialization bug that the browser would see is only visible from
    this side of the round trip.
    """
    out: dict[str, object] = {}
    for name in ("nIn", "nHidden", "nOut"):
        m = re.search(rf"\b{name}:\s*(\d+)", source)
        if m is None:
            raise ValueError(f"model.js has no {name}")
        out[name] = int(m.group(1))
    for name in ("W1", "b1", "W2", "b2"):
        m = re.search(rf"\b{name}:\s*Float32Array\.from\(\[([^\]]*)\]\)", source)
        if m is None:
            raise ValueError(f"model.js has no {name} as a Float32Array")
        vals = np.array([float(t) for t in m.group(1).split(",")], dtype=np.float64)
        # The browser holds these in a Float32Array and widens them on read;
        # mirror that rounding or the reference is not the program that runs.
        out[name] = vals.astype(np.float32).astype(np.float64)
    return out


def _softmax(z: np.ndarray) -> np.ndarray:
    """Row max subtracted before exp; without it a confident logit gives nan."""
    e = np.exp(z - z.max())
    return e / e.sum()


def numpy_forward(
    x: np.ndarray, W1: np.ndarray, b1: np.ndarray, W2: np.ndarray, b2: np.ndarray
) -> tuple[np.ndarray, np.ndarray]:
    """Vectorized forward on the exported float32 weights, in float64 arithmetic.

    Returns:
        ``(logits, probabilities)`` for a single ``(784,)`` input.
    """
    h = np.maximum(x @ W1 + b1, 0.0)
    logits = h @ W2 + b2
    return logits, _softmax(logits)


def js_equivalent_forward(x: np.ndarray, model: dict[str, object]) -> tuple[np.ndarray, np.ndarray]:
    """The forward pass as ``app.js`` writes it: flat arrays, explicit loops.

    JavaScript numbers are IEEE doubles, so this is float64 scalar arithmetic
    over the row-major flattened weights -- the point of the exercise is the
    indexing, not the precision.
    """
    n_in, n_hidden, n_out = model["nIn"], model["nHidden"], model["nOut"]
    W1, b1, W2, b2 = model["W1"], model["b1"], model["W2"], model["b2"]
    # Same loop nest and same accumulation order as app.js: input-major, so the
    # weight reads are sequential and a zero pixel can be skipped exactly. Any
    # other order would compare against a program the browser does not run.
    h = [float(v) for v in b1]
    for i in range(n_in):
        xi = float(x[i])
        if xi == 0.0:
            continue
        off = i * n_hidden
        for j in range(n_hidden):
            h[j] += xi * float(W1[off + j])
    h = [v if v > 0.0 else 0.0 for v in h]
    logits = [float(v) for v in b2]
    for j in range(n_hidden):
        hj = h[j]
        if hj == 0.0:
            continue
        off = j * n_out
        for k in range(n_out):
            logits[k] += hj * float(W2[off + k])
    logits = np.asarray(logits)
    return logits, _softmax(logits)


def consistency_check(
    js_path: str,
    W1: np.ndarray,
    b1: np.ndarray,
    W2: np.ndarray,
    b2: np.ndarray,
    rng: np.random.Generator,
    n_probe: int = 4,
    tol: float = 1e-5,
) -> tuple[float, float, bool]:
    """Compare the NumPy forward with the JS-equivalent one on the exported weights.

    Args:
        js_path: The ``model.js`` just written.
        W1, b1, W2, b2: The float32 arrays that were exported.
        rng: Explicit generator for the probe inputs.
        n_probe: Number of random ``[0, 1]`` inputs to test.
        tol: Failure threshold on the probability difference.

    Returns:
        ``(max_logit_diff, max_prob_diff, passed)``.
    """
    with open(js_path, encoding="utf-8") as fh:
        model = parse_model_js(fh.read())
    n_in = int(model["nIn"])
    worst_logit, worst_prob = 0.0, 0.0
    for _ in range(n_probe):
        # MNIST-like sparsity: most pixels are 0, a few are near 1.
        x = np.where(rng.random(n_in) < 0.18, rng.random(n_in), 0.0)
        la, pa = numpy_forward(x, W1, b1, W2, b2)
        lb, pb = js_equivalent_forward(x, model)
        worst_logit = max(worst_logit, float(np.max(np.abs(la - lb))))
        worst_prob = max(worst_prob, float(np.max(np.abs(pa - pb))))
    return worst_logit, worst_prob, worst_prob < tol and worst_logit < tol


def inline_html(index_html: str, model_js: str, app_js: str) -> str:
    """Fold ``model.js`` and ``app.js`` into ``index.html`` as one sendable file."""
    out = index_html
    for tag, body in (
        ('<script src="model.js"></script>', model_js),
        ('<script src="app.js"></script>', app_js),
    ):
        if tag not in out:
            raise ValueError(f"index.html does not contain {tag!r}")
        # </script> inside a string literal would close this block early; the
        # generated sources contain none, but split defensively anyway.
        safe = body.replace("</script>", "<\\/script>")
        out = out.replace(tag, f"<script>\n{safe}\n</script>")
    return out


def _synthetic_weights(rng: np.random.Generator, sizes: tuple[int, int, int]):
    """He-initialized untrained weights, so the export path runs with no training."""
    model = MLP(list(sizes), rng)
    d0, d1 = model.dense_layers()
    return d0.W, d0.b, d1.W, d1.b


def export(
    weights: str,
    out_js: str,
    rng: np.random.Generator,
    synthetic: bool = False,
    inline: str | None = None,
    web_dir: str = _WEB,
    verbose: bool = True,
) -> tuple[str, float, float, bool]:
    """Write ``model.js`` (and optionally the inlined HTML) and verify it.

    Returns:
        ``(path_to_model_js, max_logit_diff, max_prob_diff, passed)``.
    """
    if synthetic:
        W1, b1, W2, b2 = _synthetic_weights(rng, (784, 128, 10))
        acc = 0.0
    else:
        with np.load(weights) as z:
            W1, b1, W2, b2 = z["W1"], z["b1"], z["W2"], z["b2"]
            acc = float(z["test_accuracy"]) if "test_accuracy" in z else 0.0
    if W1.shape[1] != b1.shape[0] or W2.shape[0] != b1.shape[0] or W2.shape[1] != b2.shape[0]:
        raise ValueError(f"inconsistent shapes: {W1.shape} {b1.shape} {W2.shape} {b2.shape}")

    # Everything downstream must see the *float32* values, not the float64 ones,
    # or the check would compare the model against a model the browser never runs.
    W1, b1, W2, b2 = (np.asarray(a, dtype=np.float32).astype(np.float64) for a in (W1, b1, W2, b2))

    os.makedirs(os.path.dirname(os.path.abspath(out_js)) or ".", exist_ok=True)
    source = render_model_js(W1, b1, W2, b2, acc)
    with open(out_js, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(source)
    if verbose:
        kb = os.path.getsize(out_js) / 1024
        print(f"wrote {out_js}  ({kb:.0f} KB, {W1.size + b1.size + W2.size + b2.size:,} params)")

    dl, dp, ok = consistency_check(out_js, W1, b1, W2, b2, rng)
    if verbose:
        print(
            f"JS forward consistency: max|logit diff| = {dl:.3e}   "
            f"max|prob diff| = {dp:.3e}   {'ok' if ok else 'FAIL'} (target < 1e-5)"
        )

    if inline:
        with open(os.path.join(web_dir, "index.html"), encoding="utf-8") as fh:
            index = fh.read()
        with open(os.path.join(web_dir, "app.js"), encoding="utf-8") as fh:
            app = fh.read()
        html = inline_html(index, source, app)
        with open(inline, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(html)
        if verbose:
            print(f"wrote {inline}  ({os.path.getsize(inline) / 1024:.0f} KB, one file, sendable)")
    return out_js, dl, dp, ok


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--weights", default=os.path.join(_HERE, "weights.npz"))
    ap.add_argument("--out", default=os.path.join(_WEB, "model.js"))
    ap.add_argument(
        "--inline",
        nargs="?",
        const=os.path.join(_HERE, "mnist_demo.html"),
        default=None,
        help="also fold model.js + app.js into a single self-contained HTML file",
    )
    ap.add_argument(
        "--synthetic-weights",
        action="store_true",
        help="export untrained He-initialized weights (exercises the path offline)",
    )
    ap.add_argument("--seed", type=int, default=0)
    args = ap.parse_args(argv)

    _, _, _, ok = export(
        args.weights,
        args.out,
        np.random.default_rng(args.seed),
        synthetic=args.synthetic_weights,
        inline=args.inline,
    )
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
